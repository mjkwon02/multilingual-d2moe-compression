#!/usr/bin/env python3
"""P0-1  §6.4 korean_only intervention reproduction -- extraction only, no new runs.

PROVENANCE
  primary   : results/table5_sec54_bundle.json
              (generated by scripts/make_table5_sec54_bundle.py)
  raw runs  : results/deepseek/sec54/step2_bundle.json          (english_only seed0)
              results/deepseek/sec54/seed1_repro/step2_bundle.json   (english_only seed1)
              results/deepseek/sec54/korean_only_repro/step2_bundle.json (korean_only seed0)
  grid ref  : results/deepseek/phase1_41_headline_gate_result.json (Table 1)
  gate ref  : results/deepseek/sec54/step1_gate.json (english_only seed0 only)
  seeds     : english_only {0, 1};  korean_only {0}
  definitions unchanged from 00_docs/SEC54_PREREG.md + 00_docs/TABLE5_SEC54_BUNDLE_SOURCE.md:
      gain(pp) = dbpb%_compressed - dbpb%_intervened     (positive = damage recovered)
      vulnerable = mean(kor_Hang, swh_Latn, ben_Beng) over RAW gains
      P1 = vulnerable_mean(treatment) - vulnerable_mean(control); prereg predicts > 0
      P3 = eng_Latn gain(treatment) - eng_Latn gain(control); prereg predicts ~ 0
"""
import json, os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent
SEC54 = Path("results/deepseek/sec54")
GRID = Path("results/deepseek/phase1_41_headline_gate_result.json")

LANGS = ["eng_Latn", "kor_Hang", "zho_Hans", "swh_Latn", "ben_Beng"]
SHORT = {"eng_Latn": "EN", "kor_Hang": "KO", "zho_Hans": "ZH", "swh_Latn": "SW", "ben_Beng": "BN"}
VULN = ["kor_Hang", "swh_Latn", "ben_Beng"]

bundle = json.loads((ROOT / "results/table5_sec54_bundle.json").read_text())
grid = json.loads(GRID.read_text())["grid"]

RUN_SEED = {"english_only seed0": ("english_only", 0), "english_only seed1": ("english_only", 1),
            "korean_only seed0": ("korean_only", 0)}

out = {
    "provenance": {
        "generated_utc": "2026-08-02",
        "primary_json": "results/table5_sec54_bundle.json",
        "raw_run_paths": {k: v["path"] for k, v in bundle["runs"].items()},
        "grid_reference": str(GRID),
        "seeds_used": {"english_only": [0, 1], "korean_only": [0]},
        "metric": bundle["metric"],
        "vulnerable_set": VULN,
    },
    "runs": {},
    "integrity_B3": {},
    "gate": {},
    "comparison": {},
}

for name, r in bundle["runs"].items():
    t = r["arms"]["treatment"]["gain_pp"]
    c = r["arms"]["control"]["gain_pp"]
    tv = r["arms"]["treatment"]["vulnerable_mean_pp"]
    cv = r["arms"]["control"]["vulnerable_mean_pp"]
    # independent recomputation of the vulnerable means from raw per-language gains
    tv_re = sum(t[l] for l in VULN) / 3
    cv_re = sum(c[l] for l in VULN) / 3
    p1 = tv - cv
    p3 = t["eng_Latn"] - c["eng_Latn"]
    out["runs"][name] = {
        "in_main_table": r["in_main_table"],
        "scale_condition": r["scale_condition"],
        "treatment_gain_pp_raw": t,
        "control_gain_pp_raw": c,
        "treatment_gain_pp_rounded": {SHORT[l]: round(t[l], 3) for l in LANGS},
        "control_gain_pp_rounded": {SHORT[l]: round(c[l], 3) for l in LANGS},
        "vulnerable_mean_treatment_raw": tv,
        "vulnerable_mean_control_raw": cv,
        "vulnerable_mean_treatment_recomputed": tv_re,
        "vulnerable_mean_control_recomputed": cv_re,
        "vulnerable_mean_recompute_absdiff": {"treatment": abs(tv - tv_re), "control": abs(cv - cv_re)},
        "P1_difference_pp_raw": p1,
        "P1_difference_pp_rounded": round(p1, 3),
        "P1_matches_stored": abs(p1 - r["P1"]["difference_pp"]) < 1e-12,
        "P1_direction_holds": r["P1"]["direction_holds"],
        "P3_english_diff_pp_raw": p3,
        "P3_english_diff_pp_rounded": round(p3, 3),
        "P3_matches_stored": abs(p3 - r["P3_english_control_diff_pp"]) < 1e-12,
        "P3_over_P1_abs_ratio": abs(p3) / abs(p1) if p1 else None,
        "compressed_delta_bpb_pct": r["compressed_delta_bpb_pct"],
    }
    # ---- B-3 integrity: compressed dbpb% vs the official Table 1 grid cell ----
    cond, seed = RUN_SEED[name]
    diffs = {}
    for l in LANGS:
        official = grid[f"{cond}|{l}"]["per_seed"][seed]
        got = r["compressed_delta_bpb_pct"][l]
        diffs[l] = {"grid_official": official, "run_compressed": got,
                    "abs_diff": abs(official - got),
                    "match_6dp": round(official, 6) == round(got, 6)}
    out["integrity_B3"][name] = {
        "grid_row": cond,
        "seed": seed,
        "per_lang": diffs,
        "stored_reference_check_bpb_diff": r["reference_check_bpb_diff"],
        "all_match_6dp": all(d["match_6dp"] for d in diffs.values()),
        "max_abs_diff": max(d["abs_diff"] for d in diffs.values()),
        "STOP": not all(d["match_6dp"] for d in diffs.values()),
    }

# ---- gate info ----
g_en0 = json.loads((SEC54 / "step1_gate.json").read_text())
out["gate"]["english_only seed0"] = {
    "status": "run",
    "path": str(SEC54 / "step1_gate.json"),
    "threshold_pp": g_en0["threshold_pp"],
    "max_treatment_gain_pp": g_en0["max_treatment_gain_pp"],
    "passed_threshold": g_en0["max_treatment_gain_pp"] >= g_en0["threshold_pp"],
    "verdict": g_en0["verdict"],
    "per_treatment_pair_gain_pp": g_en0["per_treatment"],
}
for name, sub in [("english_only seed1", "seed1_repro"), ("korean_only seed0", "korean_only_repro")]:
    p = SEC54 / sub / "step1_gate.json"
    out["gate"][name] = {
        "status": "run" if p.exists() else "not_run",
        "note": ("no step1_gate.json in %s -- the 2-pair pre-gate was NOT re-run for this condition; "
                 "the run went straight to bundle mode reusing the english_only/seed0 BUNDLE_MODE verdict"
                 % (SEC54 / sub)) if not p.exists() else "",
        "dir_listing": sorted(os.listdir(SEC54 / sub)),
    }

# ---- direction-replication flags ----
ko = out["runs"]["korean_only seed0"]
en0 = out["runs"]["english_only seed0"]
en1 = out["runs"]["english_only seed1"]


def sign(x):
    return 0 if x == 0 else (1 if x > 0 else -1)


out["comparison"] = {
    "definition": ("direction_replicated = sign(korean_only seed0 statistic) equals the sign observed in "
                   "BOTH english_only seeds. This is a reproduction-of-the-english_only-pattern flag, "
                   "not a prereg verdict."),
    "P1_signs": {"english_only seed0": sign(en0["P1_difference_pp_raw"]),
                 "english_only seed1": sign(en1["P1_difference_pp_raw"]),
                 "korean_only seed0": sign(ko["P1_difference_pp_raw"])},
    "P3_signs": {"english_only seed0": sign(en0["P3_english_diff_pp_raw"]),
                 "english_only seed1": sign(en1["P3_english_diff_pp_raw"]),
                 "korean_only seed0": sign(ko["P3_english_diff_pp_raw"])},
    "P1_direction_replicated": sign(ko["P1_difference_pp_raw"]) == sign(en0["P1_difference_pp_raw"]) == sign(en1["P1_difference_pp_raw"]),
    "P3_direction_replicated": sign(ko["P3_english_diff_pp_raw"]) == sign(en0["P3_english_diff_pp_raw"]) == sign(en1["P3_english_diff_pp_raw"]),
    "P1_prereg_direction_holds": {n: out["runs"][n]["P1_direction_holds"] for n in out["runs"]},
    "negative_control_magnitude": {
        n: {"P3_english_diff_pp": out["runs"][n]["P3_english_diff_pp_raw"],
            "P1_vulnerable_diff_pp": out["runs"][n]["P1_difference_pp_raw"],
            "abs_ratio_P3_over_P1": out["runs"][n]["P3_over_P1_abs_ratio"]}
        for n in out["runs"]},
}

(OUT / "p0_1_intervention_korean.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")

# ---------------- table5_final.csv ----------------
rows = []
hdr = ["compression_condition", "seed", "row", "EN", "KO", "ZH", "SW", "BN", "vulnerable_mean"]
for name in ["english_only seed0", "english_only seed1", "korean_only seed0"]:
    r = out["runs"][name]
    cond, seed = RUN_SEED[name]
    t, c = r["treatment_gain_pp_raw"], r["control_gain_pp_raw"]
    rows.append([cond, seed, "treatment bundle (12 pairs)"] + ["%.6f" % t[l] for l in LANGS] + ["%.6f" % r["vulnerable_mean_treatment_raw"]])
    rows.append([cond, seed, "control bundle (12 pairs)"] + ["%.6f" % c[l] for l in LANGS] + ["%.6f" % r["vulnerable_mean_control_raw"]])
    rows.append([cond, seed, "difference (treatment - control)"] + ["%.6f" % (t[l] - c[l]) for l in LANGS] + ["%.6f" % r["P1_difference_pp_raw"]])

with (OUT / "table5_final.csv").open("w") as f:
    f.write("# Table 5 -- bundle restoration gain (pp). gain = dbpb%_compressed - dbpb%_intervened; positive = recovery.\n")
    f.write("# provenance: results/table5_sec54_bundle.json <- sec54/{,seed1_repro/,korean_only_repro/}step2_bundle.json\n")
    f.write("# vulnerable_mean = mean(KO,SW,BN) over RAW gains. Values at 6 dp; paper rounding is 3 dp.\n")
    f.write(",".join(hdr) + "\n")
    for r in rows:
        f.write(",".join(str(x) for x in r) + "\n")

print(json.dumps({
    "B3_all_ok": {k: v["all_match_6dp"] for k, v in out["integrity_B3"].items()},
    "B3_max_abs_diff": {k: v["max_abs_diff"] for k, v in out["integrity_B3"].items()},
    "P1_direction_replicated": out["comparison"]["P1_direction_replicated"],
    "P3_direction_replicated": out["comparison"]["P3_direction_replicated"],
    "gate_status": {k: v["status"] for k, v in out["gate"].items()},
    "ko_P1": ko["P1_difference_pp_raw"], "ko_P3": ko["P3_english_diff_pp_raw"],
    "ko_ratio": ko["P3_over_P1_abs_ratio"],
}, indent=1))
